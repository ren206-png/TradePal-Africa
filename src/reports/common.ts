import type { TenantScopedClient } from "../db/tenantScope.js";
import { isFeatureEnabled } from "../domain/featureFlags.js";
import { ACCOUNTING_FLAG } from "../domain/accounting.js";

/**
 * Bookkeeping reports (expansion Phase 8). Every report states its date range, currency, timezone and where each number came from, and
 * lists what it could NOT include. None of them says "profit": a report that cannot be complete says so in `warnings`, and a number that
 * cannot be computed honestly is reported as unavailable rather than estimated. These are bookkeeping reports, not tax filings, not
 * audited statements, and not evidence of creditworthiness.
 */
export const FLAG_REPORTS = "reportsV2";
export const MAX_RANGE_DAYS = 366;

export type ReportName = "sales" | "cash-flow" | "inventory-valuation" | "ar-aging" | "ap-aging" | "gross-margin" | "payment-reconciliation" | "stock-discrepancies";

export interface Warning {
  code: string;
  message: string;
}

export interface Source {
  /** Where the numbers came from, e.g. "journal entries", "chat ledger (Transaction)", "stock balances". */
  name: string;
  rows: number;
}

export interface ReportMeta {
  report: ReportName;
  title: string;
  currencyCode: string;
  minorUnitExp: number;
  timezone: string;
  /** Inclusive local start day and EXCLUSIVE end instant, as UTC instants. For point-in-time reports `from`/`to` are both the "as of" instant. */
  from: string;
  to: string;
  asOf: string | null;
  generatedAt: string;
  sources: Source[];
  /** How the figures were derived, in one line a merchant can read. */
  basis: string;
  warnings: Warning[];
  /** Always present: reminds the reader what this document is not. */
  notice: string;
}

export interface Report<T> {
  meta: ReportMeta;
  data: T;
}

export const NOTICE = "Bookkeeping report generated by TradePal from the records you entered and the payments TradePal could confirm. It is not a tax filing, an audited statement, or a statement of profit.";

export class ReportError extends Error {
  readonly code: "INVALID_RANGE" | "UNSUPPORTED" | "NOT_ALLOWED";
  constructor(code: ReportError["code"], message: string) {
    super(message);
    this.code = code;
  }
}

export interface ReportContext {
  scoped: TenantScopedClient;
  businessId: string;
  currencyCode: string;
  minorUnitExp: number;
  timezone: string;
  now?: Date;
}

export interface RangeInput {
  from: Date;
  to: Date;
}

export function checkRange(r: RangeInput): void {
  if (!(r.from instanceof Date) || !(r.to instanceof Date) || Number.isNaN(r.from.getTime()) || Number.isNaN(r.to.getTime())) throw new ReportError("INVALID_RANGE", "Give a valid start and end date.");
  if (r.to.getTime() <= r.from.getTime()) throw new ReportError("INVALID_RANGE", "The end must be after the start.");
  if (r.to.getTime() - r.from.getTime() > MAX_RANGE_DAYS * 86_400_000) throw new ReportError("INVALID_RANGE", `A report covers at most ${MAX_RANGE_DAYS} days.`);
}

/** The local calendar day (YYYY-MM-DD) of an instant in an IANA timezone. */
export function localDay(date: Date, timeZone: string): string {
  const parts = new Intl.DateTimeFormat("en-CA", { timeZone, year: "numeric", month: "2-digit", day: "2-digit" }).formatToParts(date);
  const v = (t: string) => parts.find((p) => p.type === t)!.value;
  return `${v("year")}-${v("month")}-${v("day")}`;
}

export function meta(ctx: ReportContext, report: ReportName, title: string, basis: string, range: RangeInput | null, sources: Source[], warnings: Warning[], asOf: Date | null = null): ReportMeta {
  const now = ctx.now ?? new Date();
  return {
    report, title, currencyCode: ctx.currencyCode, minorUnitExp: ctx.minorUnitExp, timezone: ctx.timezone,
    from: (range?.from ?? asOf ?? now).toISOString(), to: (range?.to ?? asOf ?? now).toISOString(), asOf: asOf ? asOf.toISOString() : null,
    generatedAt: now.toISOString(), sources, basis, warnings, notice: NOTICE,
  };
}

/** Are journals the book of record for this business? On when the flag is on; the report still warns when the chat ledger has entries the journal lacks. */
export async function journalsOn(ctx: ReportContext): Promise<boolean> {
  return isFeatureEnabled(ctx.scoped, ctx.businessId, ACCOUNTING_FLAG);
}

export const sumBig = (xs: bigint[]): bigint => xs.reduce((a, b) => a + b, 0n);
export const str = (v: bigint): string => v.toString();
